#!/usr/bin/env python3
"""Web deliverables: Latin subsets (WOFF2) and CSS @font-face files. MIT licensed."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import engine  # noqa: E402
from fontTools import subset  # noqa: E402
from ttcore import WEIGHTS, ps_style  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
FAM = engine.FAMILY
LATIN = "U+0020-007E,U+00A0-00FF,U+0131,U+0178,U+2013-2026,U+20AC,U+2190-2193,U+2260-2265,U+221E"
TERMINAL = "U+2500-259F,U+E0A0-E0A2,U+E0B0-E0B3"


def make_subset(src, dst, unicodes):
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    opts.glyph_names = True
    f = subset.load_font(src, opts)
    s = subset.Subsetter(opts)
    s.populate(unicodes=subset.parse_unicodes(unicodes))
    s.subset(f)
    subset.save_font(f, dst, opts)


def main():
    web = os.path.join(ROOT, "fonts", "web")
    os.makedirs(web, exist_ok=True)
    css_static, css_vf = [], []
    for w, n in WEIGHTS:
        for it in (False, True):
            base = f"{FAM['ps']}-{ps_style(w, it)}"
            src = os.path.join(ROOT, "fonts", "ttf", base + ".ttf")
            for tag, rng in (("latin", LATIN), ("terminal", TERMINAL)):
                make_subset(src, os.path.join(web, f"{base}.{tag}.woff2"), rng)
            for tag, rng in (("latin", LATIN), ("terminal", TERMINAL)):
                css_static.append(
                    f"@font-face {{\n  font-family: \"{FAM['name']}\";\n  font-style: {'italic' if it else 'normal'};\n"
                    f"  font-weight: {w};\n  font-display: swap;\n  src: url(\"../fonts/web/{base}.{tag}.woff2\") format(\"woff2\");\n"
                    f"  unicode-range: {rng};\n}}\n")
    for it in (False, True):
        vf = f"{FAM['ps']}{'-Italic' if it else ''}[wght]"
        css_vf.append(
            f"@font-face {{\n  font-family: \"{FAM['name']} Variable\";\n  font-style: {'italic' if it else 'normal'};\n"
            f"  font-weight: 100 900;\n  font-display: swap;\n  src: url(\"../fonts/variable/{vf}.woff2\") format(\"woff2-variations\"),\n"
            f"       url(\"../fonts/variable/{vf}.woff2\") format(\"woff2\");\n}}\n")
    os.makedirs(os.path.join(ROOT, "css"), exist_ok=True)
    slug = FAM["ps"].lower()
    hdr = f"/* {FAM['name']} — SIL Open Font License 1.1. Generated by tools/webfonts.py. */\n"
    with open(os.path.join(ROOT, "css", f"{slug}.css"), "w") as fh:
        fh.write(hdr + "\n".join(css_static))
    with open(os.path.join(ROOT, "css", f"{slug}-variable.css"), "w") as fh:
        fh.write(hdr + "\n".join(css_vf))
    print("web subsets + css written")


if __name__ == "__main__":
    main()
