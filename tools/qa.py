#!/usr/bin/env python3
"""QA artefacts from the compiled binaries: specimens (PNG + SVG), confusable
sheet, coverage manifest, and visual-regression diff report.

  python3 tools/qa.py specimens      # docs/specimens/*.png|svg
  python3 tools/qa.py coverage       # docs/coverage.json + docs/COVERAGE.md
  python3 tools/qa.py regress [--update]   # tests/reference/*.png, docs/visual-regression.md
MIT licensed."""
from __future__ import annotations

import json
import os
import sys
import unicodedata

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import engine  # noqa: E402
from render import label, render_line, stack, svg_line  # noqa: E402
from ttcore import WEIGHTS, ps_style  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
FAM = engine.FAMILY
CONFUSABLES = ["0O0 oOo 0Q 1lI| i!j", "5S 2Z 8B 6G 9g q", "rn m  cl d  vv w  ii u",
               "{} () [] <> ;: ,. '\" `´", "-_ – — ~ = + * x ×"]
PANGRAMS = ["SPHINX OF BLACK QUARTZ, JUDGE MY VOW", "the quick brown fox jumps over the lazy dog",
            "0123456789 $€£¥ %&@#!? ÀÉÎÕÜ àéîõü ç ñ ß"]
REGRESS = {"ascii": "".join(chr(c) for c in range(0x21, 0x7F)),
           "latin1": "".join(chr(c) for c in range(0xA1, 0x100) if c != 0xAD),
           "box": "┌─┬─┐│╳│╞═╪═╡└─┴─┘ ▀▄█▌▐░▒▓ \ue0b0\ue0b1\ue0b2\ue0b3"}


def font(w, it, kind="ttf"):
    return os.path.join(ROOT, "fonts", kind, f"{FAM['ps']}-{ps_style(w, it)}.{kind}")


def specimens():
    out = os.path.join(ROOT, "docs", "specimens")
    os.makedirs(out, exist_ok=True)
    rows = []
    for w, n in WEIGHTS:
        for it in (False, True):
            rows.append(label(f"{n}{' Italic' if it else ''}  ({w})"))
            rows.append(render_line(font(w, it), PANGRAMS[0] if not it else PANGRAMS[1], 30))
    stack(rows).save(os.path.join(out, "styles.png"))
    stack([render_line(font(400, False), t, 44) for t in PANGRAMS]).save(os.path.join(out, "regular.png"))
    stack([label("Confusable characters, Regular / Bold")] +
          [render_line(font(w, False), t, 40) for w in (400, 700) for t in CONFUSABLES]).save(
        os.path.join(out, "confusables.png"))
    stack([render_line(font(400, False), PANGRAMS[0][:24], s) for s in (8, 10, 12, 14, 16, 20, 24, 32, 48, 64)]).save(
        os.path.join(out, "waterfall.png"))
    term = ["┌─ " + FAM["name"] + " ─────────────┐", "│ $ make && ./run --fast │", "│ ▓▓▓▓▓▓▒▒░░  78%        │",
            "└────────────────────────┘", "\ue0b0 main \ue0b1 src \ue0b2 0 != O -> ok"]
    stack([render_line(font(400, False), t, 28) for t in term]).save(os.path.join(out, "terminal.png"))
    # SVG specimen from real outlines
    parts, y, width = [], 10, 0
    for w, n in WEIGHTS:
        d, wd, h = svg_line(font(w, False), f"{n} {PANGRAMS[0][:20]}", 36, y=y)
        parts.append(f'<path d="{d}"/>')
        y += h + 6
        width = max(width, wd)
    with open(os.path.join(out, "weights.svg"), "w") as fh:
        fh.write(f'<svg xmlns="http://www.w3.org/2000/svg" width="{int(width) + 20}" height="{int(y) + 10}">'
                 f'<rect width="100%" height="100%" fill="#fff"/><g fill="#111">{"".join(parts)}</g></svg>\n')
    print("specimens ->", out)


def coverage():
    from fontTools.ttLib import TTFont
    tt = TTFont(font(400, False))
    cmap = tt.getBestCmap()
    blocks = {}
    for cp in sorted(cmap):
        if 0xE000 <= cp <= 0xF8FF:
            b = "Private Use (Powerline)"
        elif cp < 0x80:
            b = "Basic Latin"
        elif cp < 0x100:
            b = "Latin-1 Supplement"
        elif cp < 0x180:
            b = "Latin Extended-A"
        elif 0x2000 <= cp < 0x2070:
            b = "General Punctuation"
        elif 0x20A0 <= cp < 0x20D0:
            b = "Currency Symbols"
        elif 0x2190 <= cp < 0x2200:
            b = "Arrows"
        elif 0x2200 <= cp < 0x2300:
            b = "Mathematical Operators"
        elif 0x2500 <= cp < 0x2580:
            b = "Box Drawing"
        elif 0x2580 <= cp < 0x25A0:
            b = "Block Elements"
        else:
            b = "Other"
        blocks.setdefault(b, []).append(cp)
    ascii_missing = [f"U+{c:04X}" for c in range(0x20, 0x7F) if c not in cmap]
    latin1_missing = [f"U+{c:04X}" for c in range(0xA0, 0x100) if c not in cmap]
    data = {"family": FAM["name"], "glyphs": len(tt.getGlyphOrder()), "codepoints": len(cmap),
            "blocks": {k: {"count": len(v), "codepoints": [f"U+{c:04X}" for c in v]} for k, v in blocks.items()},
            "ascii_missing": ascii_missing, "latin1_missing": latin1_missing}
    os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
    with open(os.path.join(ROOT, "docs", "coverage.json"), "w") as fh:
        json.dump(data, fh, indent=1)
    lines = [f"# {FAM['name']} coverage manifest", "", "Generated by `tools/qa.py coverage` from the compiled Regular TTF.", "",
             f"* Glyphs: **{data['glyphs']}** (including alternates and .notdef)", f"* Encoded code points: **{data['codepoints']}**",
             f"* Printable ASCII (U+0020–U+007E) missing: {', '.join(ascii_missing) or 'none'}",
             f"* Latin-1 Supplement (U+00A0–U+00FF) missing: {', '.join(latin1_missing) or 'none'}", "",
             "| Block | Code points |", "|---|---|"]
    lines += [f"| {k} | {len(v)} |" for k, v in blocks.items()]
    with open(os.path.join(ROOT, "docs", "COVERAGE.md"), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(json.dumps({k: v for k, v in data.items() if k != "blocks"}))


def regress(update=False):
    import numpy as np
    from PIL import Image
    ref = os.path.join(ROOT, "tests", "reference")
    cur = os.path.join(ROOT, "build", "regress")
    os.makedirs(ref, exist_ok=True)
    os.makedirs(cur, exist_ok=True)
    report = [f"# {FAM['name']} visual regression", "",
              "Each sheet is rendered from the compiled TTF with HarfBuzz + FreeType (unhinted, 32 px) and compared",
              "pixel-by-pixel with `tests/reference/`. Refresh references deliberately with `python3 tools/qa.py regress --update`.", "",
              "| Sheet | Changed pixels | Max delta | Status |", "|---|---|---|---|"]
    worst = 0
    for w, n in WEIGHTS:
        for it in (False, True):
            for key, text in REGRESS.items():
                fn = f"{ps_style(w, it)}-{key}.png"
                img = render_line(font(w, it), text, 32)
                img.save(os.path.join(cur, fn))
                rp = os.path.join(ref, fn)
                if update or not os.path.exists(rp):
                    img.save(rp)
                    report.append(f"| {fn} | – | – | reference written |")
                    continue
                a = np.asarray(Image.open(rp), dtype=np.int16)
                b = np.asarray(img, dtype=np.int16)
                if a.shape != b.shape:
                    report.append(f"| {fn} | size {a.shape}→{b.shape} | – | **CHANGED** |")
                    worst = max(worst, 1)
                    continue
                diff = np.abs(a - b)
                changed = int((diff > 32).sum())
                worst = max(worst, changed)
                report.append(f"| {fn} | {changed} | {int(diff.max())} | {'ok' if changed == 0 else '**CHANGED**'} |")
    with open(os.path.join(ROOT, "docs", "visual-regression.md"), "w") as fh:
        fh.write("\n".join(report) + "\n")
    print("regress worst changed pixels:", worst)
    return worst


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "all"
    if cmd in ("specimens", "all"):
        specimens()
    if cmd in ("coverage", "all"):
        coverage()
    if cmd in ("regress", "all"):
        sys.exit(1 if regress("--update" in sys.argv) else 0)
